#!/usr/bin/env bash
# Shared manifest integrity and managed-entry contracts; no kit checkout required.
AGENTS_BEGIN='<!-- BEGIN PRODUCT-KIT MANAGED SECTION - do not edit inside; regenerated by init.sh -->'
AGENTS_END='<!-- END PRODUCT-KIT MANAGED SECTION -->'
MEMORY_SEEDS="constitution-template.md:constitution.md agents-template.md:agents.md config-template.md:config.md"

# Shared installation mapping, for filesystem installation and committed-object proof.
# Input is a kit-relative file, never a path taken from a consumer manifest.
install_file_selected() { # source-path options
    case "$1" in
        scripts/render-agents.sh|templates/agent-definition-template.md)
            case " $2 " in *' agent-tiers '*) return 0 ;; *) return 1 ;; esac ;;
    esac
    return 0
}

install_file_targets() { # source-path harnesses options [literal output prefix]
    local src="$1" harnesses=" $2 " base="${1##*/}" prefix="${4:-}" pair
    install_file_selected "$src" "$3" || return 0
    case "$src" in
        commands/prdkit*.md)
            case "$harnesses" in *' claude '*) printf '%s.claude/commands/%s\n' "$prefix" "$base" || return 1 ;; esac
            case "$harnesses" in *' opencode '*) printf '%s.opencode/commands/%s\n' "$prefix" "$base" || return 1 ;; esac ;;
        workflows/*.md) printf '%s.prdkit/workflows/%s\n' "$prefix" "$base" ;;
        scripts/init.sh) ;;
        scripts/*.sh|scripts/pr-facts.py|scripts/facts.py|scripts/agents-section.md|scripts/outcome-checkpoint.md)
            printf '%s.prdkit/scripts/bash/%s\n' "$prefix" "$base" ;;
        templates/*.md)
            printf '%s.prdkit/templates/%s\n' "$prefix" "$base" || return 1
            for pair in $MEMORY_SEEDS; do
                if [ "$base" = "${pair%%:*}" ]; then
                    printf '%s.prdkit/memory/%s\n' "$prefix" "${pair#*:}" || return 1
                fi
            done ;;
    esac
}

install_hash_stream() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -d ' ' -f 1
    else shasum -a 256 | cut -d ' ' -f 1; fi
}

# BSD head rejects -c 0. An empty prefix still opens its input so a missing or
# unreadable file fails rather than silently becoming successful empty evidence.
install_head_bytes() { # nonnegative count file
    case "$1" in ''|*[!0-9]*) return 1 ;; esac
    if [ "$1" -eq 0 ]; then : < "$2"
    else head -c "$1" "$2"; fi
}

render_agents_section() {
    cat "$(dirname "${BASH_SOURCE[0]}")/agents-section.md"
}

managed_agents_section() {
    local newline=1 last last_line
    [ -f "$1" ] || return 1
    # Validate raw text before tail, shell strings or awk can discard input bytes.
    # Load the shared byte-safe contract in isolation for standalone library callers too.
    (source "$(dirname "${BASH_SOURCE[0]}")/common.sh" && review_file_without_nul "$1") || return 1
    # A line printer must not invent a terminator that the managed bytes did not have.
    last="$(tail -c 1 "$1" && printf x)" || return 1
    if [ "$last" != $'\nx' ]; then
        last_line="$(tail -n 1 "$1")" || return 1
        if [ "$last_line" = "$AGENTS_END" ]; then newline=0; fi
    fi
    LC_ALL=C awk -v begin="$AGENTS_BEGIN" -v end="$AGENTS_END" -v newline="$newline" '
        $0 == begin { starts++; if(section || ends) bad=1; section=1 }
        section { if($0 == end && !newline) printf "%s", $0; else print }
        $0 == end { ends++; if(!section) bad=1; section=0 }
        END { if(starts != 1 || ends != 1 || section || bad) exit 1 }
    ' "$1"
}

# Replace only the managed bytes. awk prints a final newline even when the original
# suffix had none; retain that suffix byte-for-byte rather than changing consumer text.
render_agents_replacement() { # input section-file output (distinct from input)
    local size tmp
    awk -v b="$AGENTS_BEGIN" -v e="$AGENTS_END" -v f="$2" '
        $0 == b { while ((getline l < f) > 0) print l; skip = 1; next }
        $0 == e { skip = 0; next }
        !skip { print }
    ' "$1" > "$3" || return 1
    if [ -n "$(tail -c 1 "$1")" ] && [ "$(tail -n 1 "$1")" != "$AGENTS_END" ]; then
        size="$(wc -c < "$3" | tr -d '[:space:]')" || return 1
        tmp="$(mktemp "$3.suffix.XXXXXX")" || return 1
        if install_head_bytes "$((size - 1))" "$3" > "$tmp" && cat "$tmp" > "$3"; then rm -f "$tmp"
        else rm -f "$tmp"; return 1; fi
    fi
}

install_manifest_value() {
    awk -v prefix="$2: " 'index($0,prefix) == 1 {
        count++; value=substr($0,length(prefix)+1)
    } END { if(count != 1 || value == "") exit 1; print value }' "$1"
}

install_manifest_format() {
    local mode options
    verify_lf_file "$1" &&
        install_manifest_value "$1" version >/dev/null &&
        install_manifest_value "$1" harnesses >/dev/null &&
        mode="$(install_manifest_value "$1" mode)" &&
        options="$(install_manifest_value "$1" options)" || return 1
    case "$mode" in copy|symlink) ;; *) return 1 ;; esac
    case "$options" in none|agent-tiers) ;; *) return 1 ;; esac
    LC_ALL=C awk '
        /^(version|harnesses|mode|options|agents-section): / { next }
        NF == 0 { next }
        length($1) == 64 && $1 ~ /^[0-9a-f]+$/ && substr($0, 65, 2) == "  " &&
            substr($0, 67) ~ /^(\.(claude|opencode)\/commands\/prdkit[^\/]*\.md|\.prdkit\/(scripts\/bash|templates|memory|workflows)\/[A-Za-z0-9_.-]+)$/ &&
            substr($0, 67) !~ /\/\.\.?$/ { next }
        { bad = 1 }
        END { exit bad }
    ' "$1"
}

# Exact stage-0 gitlink only: a directory pathspec also matches nested submodules.
install_source_pin() {
    git -C "$1" ls-files -s -- ":(literal)$2" 2>/dev/null |
        awk -v path="$2" '$1 == 160000 && $3 == 0 && substr($0, index($0, "\t") + 1) == path { n++; pin=$2 } END { if(n == 1) print pin }'
}

# Print findings, rather than mutating any installation. Project-owned hashes may differ.
install_findings() {
    local root="$1" manifest="$1/.prdkit/.manifest" harnesses mode line hash path actual section expected dir artifacts
    local owned=0 checked=0
    if git -C "$root" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        artifacts="$(verify_lines git -C "$root" ls-files -- .prdkit/.install-lock .prdkit/.install-state)" || return 1
        while IFS= read -r path; do
            [ -z "$path" ] || printf 'Tracked installer runtime artifact: %s; remove it from the index and keep it ignored\n' "$path"
        done <<< "$artifacts"
    fi
    if [ -e "$root/.prdkit/.install-state" ] || [ -L "$root/.prdkit/.install-state" ]; then
        printf 'Incomplete install: .prdkit/.install-state remains; inspect it and retry the same source with init.sh --upgrade\n'
    fi
    if [ ! -f "$manifest" ]; then printf 'Missing installed file: .prdkit/.manifest\n'; return 0; fi
    if ! verify_lf_file "$manifest"; then printf 'Invalid install manifest: expected non-empty LF-terminated text\n'; return 0; fi
    expected="$(wc -l < "$manifest")" || return 1
    install_manifest_value "$manifest" version >/dev/null || printf 'Manifest must record exactly one version\n'
    harnesses="$(install_manifest_value "$manifest" harnesses || true)"
    [ -n "$harnesses" ] || printf 'Manifest must record configured harnesses\n'
    mode="$(install_manifest_value "$manifest" mode || true)"
    case "$mode" in copy|symlink) ;; *) printf 'Invalid manifest install mode: %s\n' "$mode" ;; esac
    install_manifest_format "$manifest" ||
        printf 'Invalid install manifest: expected version, harnesses, mode (copy or symlink), and options (none or agent-tiers)\n'
    while IFS= read -r line; do
        checked=$((checked + 1))
        case "$line" in version:*|harnesses:*|mode:*|options:*|agents-section:*|'') continue ;; esac
        hash="${line%%  *}"; path="${line#*  }"
        if ! [[ "$hash" =~ ^[0-9a-f]{64}$ ]]; then printf 'Invalid manifest hash entry: %s\n' "$line"; continue; fi
        case "$path" in
            /*|../*|*/../*|*/..|*'//'*) printf 'Invalid manifest path: %s\n' "$path"; continue ;;
        esac
        if [ ! -f "$root/$path" ]; then printf 'Missing installed file: %s\n' "$path"; continue; fi
        case "$path" in
            .prdkit/scripts/bash/*|.prdkit/workflows/*|.claude/commands/*|.opencode/commands/*)
                owned=$((owned + 1))
                actual="$(install_hash_stream < "$root/$path")" || { printf 'Unable to hash installed file: %s\n' "$path"; continue; }
                [ "$actual" = "$hash" ] || printf 'Kit-owned content drift: %s\n' "$path" ;;
        esac
    done < "$manifest"
    [ "$checked" -eq "$expected" ] || printf 'Incomplete install manifest: expected %s lines, checked %s\n' "$expected" "$checked"
    [ "$owned" -gt 0 ] || printf 'Manifest records no installed kit-owned files\n'
    # Kit-named commands on disk that the manifest does not record: a harness the manifest
    # no longer lists (an upgrade run with a narrower --harness) or a hand-made command. The
    # contract is the manifest, so an unrecorded command file is never silently served.
    for dir in .claude/commands .opencode/commands; do
        for path in "$root/$dir"/prdkit*.md; do
            { [ -e "$path" ] || [ -L "$path" ]; } || continue
            path="${path#"$root"/}"
            awk -v p="$path" 'length($1) == 64 && $1 ~ /^[0-9a-f]+$/ && substr($0, 67) == p { found = 1 } END { exit !found }' "$manifest" ||
                printf 'Unexpected kit-named command not recorded in the manifest: %s (if a harness was dropped, re-run init.sh --upgrade --harness with the full list)\n' "$path"
        done
    done
    for path in $(printf '%s' "$harnesses" | tr ',' ' '); do
        case "$path" in claude|opencode|agents|codex) ;; *) printf 'Unknown manifest harness: %s\n' "$path" ;; esac
    done
    case " $(printf '%s' "$harnesses" | tr ',' ' ') " in
        *' agents '*|*' codex '*)
            if section="$(managed_agents_section "$root/AGENTS.md" && printf x)"; then
                section="${section%x}"
                expected="$(install_manifest_value "$manifest" agents-section || true)"
                if [ -n "$expected" ]; then
                    actual="$(printf '%s' "$section" | install_hash_stream)" || return 1
                    [ "$actual" = "$expected" ] || printf 'Kit-owned AGENTS.md managed section drift\n'
                else
                    expected="$(render_agents_section && printf x)" || return 1
                    [ "$section" = "${expected%x}" ] || printf 'AGENTS.md managed section does not match the installed entry contract\n'
                fi
            else printf 'Missing or malformed Product-Kit managed section in AGENTS.md\n'; fi ;;
    esac
}
