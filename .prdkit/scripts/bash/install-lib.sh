#!/usr/bin/env bash
# Shared manifest integrity and managed-entry contracts; no kit checkout required.
AGENTS_BEGIN='<!-- BEGIN PRODUCT-KIT MANAGED SECTION - do not edit inside; regenerated by init.sh -->'
AGENTS_END='<!-- END PRODUCT-KIT MANAGED SECTION -->'

install_hash_stream() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -d ' ' -f 1
    else shasum -a 256 | cut -d ' ' -f 1; fi
}

render_agents_section() {
    printf '%s\n' "$AGENTS_BEGIN"
    cat <<'EOF'
## Product-Kit workflow

This project uses Product-Kit. For product or development requests, read
`.prdkit/workflows/protocol.md` first; `.prdkit/workflows/README.md` indexes the rest.
A generated plan never grants action authority. Resume from the open change record and
actual repository state, not chat memory.

- `specs/product.md` and `specs/product/` (L0: journeys, then what must be true) and
  `specs/architecture.md` (L1) — why the system is shaped as it is; `specs/parts/` (L2) — what
  each part guarantees. `specs/product/lifecycle.md` names the current stage: build for it, and
  build an item marked `from:` a later stage only on owner direction.
- `specs/changes/<id>.md` — open changes with acceptance and State; `specs/log.md` — closed ones.
  Constraints, non-goals and qualities bind every change: `.prdkit/scripts/bash/bounds.sh <id>`
  lists those in its scope. Never build past a conflict; it goes to the owner.
- `specs/inbox.md` — owner direction and open questions; read its open items on resume.
- `specs/records.md` — holds, waivers, attestations and deployments.
- `.prdkit/memory/constitution.md` — owner, action policy, commands and review policy.

Everyday entry points are `/prdkit` and `/prdkit-status`; the others are `/prdkit-product`,
`/prdkit-target`, `/prdkit-learn`, `/prdkit-init`, `/prdkit-configure` and `/prdkit-doctor`.
Without native slash commands, follow the matching installed playbook. Status and doctor are
read-only. Raw evidence stays in CI or the gitignored `.prdkit/cache/evidence/`, never `specs/`.
EOF
    printf '%s\n' "$AGENTS_END"
}

managed_agents_section() {
    [ -f "$1" ] || return 1
    awk -v begin="$AGENTS_BEGIN" -v end="$AGENTS_END" '
        $0 == begin { starts++; if(section || ends) bad=1; section=1 }
        section { print }
        $0 == end { ends++; if(!section) bad=1; section=0 }
        END { if(starts != 1 || ends != 1 || section || bad) exit 1 }
    ' "$1"
}

install_manifest_value() {
    awk -v prefix="$2: " 'index($0,prefix) == 1 {
        count++; value=substr($0,length(prefix)+1)
    } END { if(count != 1 || value == "") exit 1; print value }' "$1"
}

# Print findings, rather than mutating any installation. Project-owned hashes may differ.
install_findings() {
    local root="$1" manifest="$1/.prdkit/.manifest" harnesses mode line hash path actual section expected dir
    local owned=0
    if [ ! -f "$manifest" ]; then printf 'Missing installed file: .prdkit/.manifest\n'; return 0; fi
    install_manifest_value "$manifest" version >/dev/null || printf 'Manifest must record exactly one version\n'
    harnesses="$(install_manifest_value "$manifest" harnesses || true)"
    [ -n "$harnesses" ] || printf 'Manifest must record configured harnesses\n'
    mode="$(install_manifest_value "$manifest" mode || true)"; mode="${mode:-symlink}"
    case "$mode" in copy|symlink) ;; *) printf 'Invalid manifest install mode: %s\n' "$mode" ;; esac
    while IFS= read -r line; do
        case "$line" in version:*|harnesses:*|mode:*|agents-section:*|'') continue ;; esac
        hash="${line%%  *}"; path="${line#*  }"
        if ! [[ "$hash" =~ ^[0-9a-f]{64}$ ]]; then printf 'Invalid manifest hash entry: %s\n' "$line"; continue; fi
        case "$path" in
            /*|../*|*/../*|*/..|*'//'*) printf 'Invalid manifest path: %s\n' "$path"; continue ;;
        esac
        if [ ! -f "$root/$path" ]; then printf 'Missing installed file: %s\n' "$path"; continue; fi
        case "$path" in
            .prdkit/scripts/bash/*|.prdkit/workflows/*|.claude/commands/*|.opencode/commands/*)
                owned=$((owned + 1))
                actual="$(install_hash_stream < "$root/$path")" || { printf 'Unable to hash installed file: %s\n' "$path"; continue; }
                [ "$actual" = "$hash" ] || printf 'Kit-owned content drift: %s\n' "$path" ;;
        esac
    done < "$manifest"
    [ "$owned" -gt 0 ] || printf 'Manifest records no installed kit-owned files\n'
    # Kit-named commands on disk that the manifest does not record: a harness the manifest
    # no longer lists (an upgrade run with a narrower --harness) or a hand-made command. The
    # contract is the manifest, so an unrecorded command file is never silently served.
    for dir in .claude/commands .opencode/commands; do
        for path in "$root/$dir"/prdkit*.md; do
            { [ -e "$path" ] || [ -L "$path" ]; } || continue
            path="${path#"$root"/}"
            awk -v p="$path" '$1 ~ /^[0-9a-f]{64}$/ && substr($0, 67) == p { found = 1 } END { exit !found }' "$manifest" ||
                printf 'Unexpected kit-named command not recorded in the manifest: %s (if a harness was dropped, re-run init.sh --upgrade --harness with the full list)\n' "$path"
        done
    done
    for path in $(printf '%s' "$harnesses" | tr ',' ' '); do
        case "$path" in claude|opencode|agents|codex) ;; *) printf 'Unknown manifest harness: %s\n' "$path" ;; esac
    done
    case " $(printf '%s' "$harnesses" | tr ',' ' ') " in
        *' agents '*|*' codex '*)
            if section="$(managed_agents_section "$root/AGENTS.md")"; then
                expected="$(install_manifest_value "$manifest" agents-section || true)"
                if [ -n "$expected" ]; then
                    actual="$(printf '%s\n' "$section" | install_hash_stream)"
                    [ "$actual" = "$expected" ] || printf 'Kit-owned AGENTS.md managed section drift\n'
                elif [ "$section" != "$(render_agents_section)" ]; then
                    printf 'AGENTS.md managed section does not match the installed entry contract\n'
                fi
            else printf 'Missing or malformed Product-Kit managed section in AGENTS.md\n'; fi ;;
    esac
}
